def write_pymol_clusters(
    conditions: Dict[str, "object"],
    baseline_name: str,
    cluster_labels: Dict[str, int],
    pymol_dir: Path,
    cluster_separation: Optional[dict] = None,
) -> None:
    cl_dir = pymol_dir / "06_clusters"
    cl_dir.mkdir(parents=True, exist_ok=True)

    anchor = baseline_name
    anchor_cif = conditions[anchor].cif_path.resolve()
    names = sorted(conditions)

    # colour-definition preamble
    def _color_defs(script_dir):
        defs = []
        n_clusters = max(cluster_labels.values()) if cluster_labels else 1
        for cid in range(1, n_clusters + 1):
            r, g, b = _CLUSTER_RGB[(cid - 1) % len(_CLUSTER_RGB)]
            defs.append(f"set_color clust{cid}, [{r:.3f}, {g:.3f}, {b:.3f}]")
        return defs

    # 06_clusters.pml — everything, coloured by cluster
    l = _header("AF3 conditions coloured by structural cluster",
                f"alignment anchor: {anchor}")
    l += _color_defs(pymol_dir)
    l += [f"load {_rel(anchor_cif, pymol_dir)}, {anchor}", ""]
    for name in names:
        if name == anchor:
            continue
        cif = conditions[name].cif_path.resolve()
        l += [
            f"load {_rel(cif, pymol_dir)}, {name}",
            f"align {name}, {anchor}",
            "",
        ]
    l += _FOOTER
    for name in names:
        cid = cluster_labels.get(name, 1)
        l.append(f"color clust{cid}, {name}")
    l += [
        "",
        "# clusters group conditions by overall Cα RMSD similarity",
    ]
    if cluster_separation and cluster_separation.get("separation_adequate") is False:
        bm = cluster_separation.get("between_condition_median_rmsd_A")
        nf = cluster_separation.get("within_condition_noise_floor_A")
        l += [
            f"# WARNING: clusters are EXPLORATORY. Between-condition RMSD (median {bm} A)",
            f"# is within the within-condition sampling-noise floor ({nf} A), so these",
            "# colours are NOT robustly separable from AF3 ensemble noise and should not",
            "# be interpreted as distinct conformational states.",
        ]
    (pymol_dir / "06_clusters.pml").write_text("\n".join(l) + "\n", encoding="utf-8")

    # per-cluster overlays
    clusters: Dict[int, List[str]] = {}
    for name, cid in cluster_labels.items():
        clusters.setdefault(cid, []).append(name)

    for cid, members in sorted(clusters.items()):
        members = sorted(members)
        ref = members[0]
        ref_cif = conditions[ref].cif_path.resolve()
        lc = _header(f"Structural cluster {cid}",
                     f"members: {', '.join(members)}")
        lc += [f"load {_rel(ref_cif, cl_dir)}, {ref}", ""]
        for idx, name in enumerate(members[1:]):
            cif = conditions[name].cif_path.resolve()
            color = _PALETTE[idx % len(_PALETTE)]
            lc += [
                f"load {_rel(cif, cl_dir)}, {name}",
                f"align {name}, {ref}",
                f"color {color}, {name}",
                "",
            ]
        lc += _FOOTER
        (cl_dir / f"cluster_{cid}.pml").write_text("\n".join(lc) + "\n", encoding="utf-8")


# ---------------------------------------------------------------------------
# Batch rendering + documentation
# ---------------------------------------------------------------------------

def _write_render_all(
    pymol_dir: Path,
    conditions: Dict[str, "object"],
    baseline_name: str,
    profiles: Optional[Dict[str, dict]],
    cluster_labels: Optional[Dict[str, int]],
) -> None:
    """
    Write render_all.pml that runs every scene headlessly and saves a PNG next
    to each .pml.  Intended for:  pymol -cq render_all.pml

    Each scene script ends with a commented ``ray``/``png`` line; here we drive
    them in batch by @-including the script and issuing the ray/png explicitly.
    """
    others = [n for n in sorted(conditions) if n != baseline_name]
    ptm_conditions = [n for n in others if _ptm_sites(conditions[n])]
    n_clusters = max(cluster_labels.values()) if cluster_labels else 0

    lines = [
        "# render_all.pml - batch-render every af3bench scene to PNG",
        "# Usage:  pymol -cq render_all.pml",
        "#         (requires a PyMOL install on PATH)",
        "set ray_trace_mode, 1",
        "set ray_shadows, 0",
        "",
    ]

    def _block(rel_script: str, png_rel: str):
        return [
            f"@{rel_script}",
            f"ray 1600, 1200",
            f"png {png_rel}, dpi=300",
            "reinitialize",
            "",
        ]

    if profiles:
        for name in profiles:
            if name not in conditions:
                continue
            lines += _block(f"04_displacement_putty/{name}.pml",
                            f"04_displacement_putty/{name}_displacement.png")
        for name in ptm_conditions:
            lines += _block(f"05_ptm_focus/{name}.pml",
                            f"05_ptm_focus/{name}_ptm_focus.png")
    if n_clusters:
        lines += _block("06_clusters.pml", "06_clusters/all_clusters.png")
        for cid in range(1, n_clusters + 1):
            lines += _block(f"06_clusters/cluster_{cid}.pml",
                            f"06_clusters/cluster_{cid}.png")

    (pymol_dir / "render_all.pml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_readme(pymol_dir: Path, has_disp: bool, has_clusters: bool) -> None:
    lines = [
        "# PyMOL scenes — af3bench",
        "",
        "Open any scene with:  `pymol <scene>.pml`",
        "Batch-render all scenes to PNG (headless):  `pymol -cq render_all.pml`",
        "",
        "## Scenes",
        "- `01_overlay.pml` — all conditions aligned to baseline, one colour each.",
        "- `02_plddt.pml` — all conditions coloured by pLDDT (blue high, red low).",
        "- `03_per_condition/` — baseline (grey) vs one condition coloured by pLDDT.",
    ]
    if has_disp:
        lines += [
            "- `04_displacement_putty/` — each condition as a cartoon *putty*: tube",
            "  thickness and blue→red colour both encode per-residue Cα displacement",
            "  vs the baseline (Å, written into the B-factor). PTM site = magenta sticks.",
            "- `05_ptm_focus/` — close-up on the modified residue (TPO/SEP), shown as",
            "  magenta sticks beside the baseline equivalent (grey), neighbourhood within",
            "  6 Å as sticks, backbone coloured by displacement.",
        ]
    if has_clusters:
        lines += [
            "- `06_clusters.pml` — every condition coloured by its structural cluster.",
            "- `06_clusters/cluster_<k>.pml` — overlay of the members of one cluster.",
        ]
    lines += [
        "",
        "## Notes",
        "- Displacement is colour-capped at the global 95% CI ceiling so scenes are",
        "  directly comparable across conditions.",
        "- B-factors in scenes 04/05 are **displacement in Å**, not pLDDT.",
        "",
    ]
    (pymol_dir / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
