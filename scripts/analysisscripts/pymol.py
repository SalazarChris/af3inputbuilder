"""
PyMOL scene generation.

Writes portable .pml scripts (relative paths where possible):

  01_overlay.pml              all conditions aligned to baseline, by condition
  02_plddt.pml                all conditions, pLDDT spectrum
  03_per_condition/           one per condition, condition coloured by pLDDT
  04_displacement_putty/      one per condition: cartoon "putty" whose radius +
                              colour encode per-residue Cα displacement vs the
                              baseline (B-factor is overwritten with displacement)
  05_ptm_focus/               one per PTM condition: close-up on the modified
                              residue with surrounding displacement context
  06_clusters.pml             all conditions coloured by structural cluster
  06_clusters/cluster_<k>.pml per-cluster overlay

Displacement scenes work by overwriting each residue's B-factor with its
displacement (Å) through ``alter`` commands, then colouring by B.  This keeps
the scripts self-contained — no external data files are needed in PyMOL.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path
from typing import Dict, List, Optional

log = logging.getLogger("af3bench.pymol")

_PALETTE = [
    "marine", "salmon", "forest", "tv_orange", "slate",
    "hotpink", "cyan", "tv_yellow", "limon", "violet",
    "deeppurple", "teal", "firebrick", "olive", "skyblue",
]

# Cluster colours mirror plots/clusters.py (Okabe-Ito-ish), as PyMOL RGB.
_CLUSTER_RGB = [
    (0.00, 0.45, 0.70), (0.84, 0.37, 0.00), (0.00, 0.62, 0.45),
    (0.80, 0.47, 0.65), (0.90, 0.62, 0.00), (0.34, 0.71, 0.91),
    (0.94, 0.89, 0.26), (0.60, 0.60, 0.60), (0.07, 0.47, 0.20),
    (0.53, 0.13, 0.33),
]

_SETTINGS = [
    "reinitialize",
    "bg_color white",
    "set ray_opaque_background, off",
    "set cartoon_fancy_helices, 1",
    "set cartoon_smooth_loops, 1",
    "set cartoon_side_chain_helper, 1",
    "set depth_cue, 0",
    "set specular, 0.2",
    "set label_size, 16",
    "set label_color, black",
    "set label_outline_color, white",
    "",
]

_FOOTER = [
    "",
    "hide everything",
    "show cartoon, polymer",
    "# show sticks, organic   # ligands",
    "# show spheres, inorganic  # ions",
    "",
    "zoom polymer",
    "orient",
    "",
]


def _header(title: str, note: str = "") -> List[str]:
    lines = [f"# {title}"]
    if note:
        lines.append(f"# {note}")
    lines += ["# Generated by af3bench", "#"]
    return lines + _SETTINGS


def _rel(cif_path: Path, script_dir: Path) -> str:
    try:
        return Path(os.path.relpath(cif_path.resolve(), script_dir.resolve())).as_posix()
    except ValueError:
        return cif_path.resolve().as_posix()


def _ptm_sites(model) -> List[tuple]:
    """Return [(chain_id, resnum, label), ...] for PTMs on a model."""
    out = []
    prot_chain = (model.protein_chain_ids_from_json or
                  (model.ca_chain_ids[:1] if model.ca_chain_ids else ["A"]))[0]
    for lab in getattr(model, "ptm_labels", []) or []:
        digits = "".join(c for c in lab if c.isdigit())
        if digits:
            out.append((prot_chain, int(digits), lab))
    return out


# ---------------------------------------------------------------------------
# Core overlays / pLDDT (unchanged behaviour, kept self-contained)
# ---------------------------------------------------------------------------

def write_pymol_baseline(
    conditions: Dict[str, "object"],
    baseline_name: str,
    output_dir: Path,
    profiles: Optional[Dict[str, dict]] = None,
    cluster_labels: Optional[Dict[str, int]] = None,
    global_disp_max: Optional[float] = None,
    cluster_separation: Optional[dict] = None,
) -> None:
    pymol_dir = output_dir / "pymol"
    pymol_dir.mkdir(parents=True, exist_ok=True)
    per_dir = pymol_dir / "03_per_condition"
    per_dir.mkdir(parents=True, exist_ok=True)

    base_cif = conditions[baseline_name].cif_path.resolve()
    others = [n for n in sorted(conditions) if n != baseline_name]

    # 01 overlay
    lines = _header("AF3 condition overlay vs baseline", f"baseline: {baseline_name}")
    lines += [
        f"load {_rel(base_cif, pymol_dir)}, BASE_{baseline_name}",
        f"color grey70, BASE_{baseline_name}",
        f"set cartoon_transparency, 0.35, BASE_{baseline_name}",
        "",
    ]
    for idx, name in enumerate(others):
        cif = conditions[name].cif_path.resolve()
        color = _PALETTE[idx % len(_PALETTE)]
        lines += [
            f"load {_rel(cif, pymol_dir)}, COND_{name}",
            f"align COND_{name}, BASE_{baseline_name}",
            f"color {color}, COND_{name}",
            "",
        ]
    lines += _FOOTER
    (pymol_dir / "01_overlay.pml").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # 02 plddt
    lines2 = _header("AF3 pLDDT map", "B-factor = pLDDT; blue=high, red=low")
    lines2 += [f"load {_rel(base_cif, pymol_dir)}, BASE_{baseline_name}", ""]
    for name in others:
        cif = conditions[name].cif_path.resolve()
        lines2 += [
            f"load {_rel(cif, pymol_dir)}, COND_{name}",
            f"align COND_{name}, BASE_{baseline_name}",
            "",
        ]
    lines2 += _FOOTER
    lines2 += ["spectrum b, blue_white_red, polymer, minimum=50, maximum=100"]
    (pymol_dir / "02_plddt.pml").write_text("\n".join(lines2) + "\n", encoding="utf-8")

    # 03 per condition (pLDDT)
    for idx, name in enumerate(others):
        cif = conditions[name].cif_path.resolve()
        l3 = _header(f"AF3: {name} vs {baseline_name}",
                     "baseline grey, condition coloured by pLDDT")
        l3 += [
            f"load {_rel(base_cif, per_dir)}, BASE_{baseline_name}",
            f"color grey70, BASE_{baseline_name}",
            f"set cartoon_transparency, 0.35, BASE_{baseline_name}",
            "",
            f"load {_rel(cif, per_dir)}, COND_{name}",
            f"align COND_{name}, BASE_{baseline_name}",
            "",
        ]
        l3 += _FOOTER
        l3 += [
            f"spectrum b, blue_white_red, COND_{name}, minimum=50, maximum=100",
            f"color grey70, BASE_{baseline_name}",
        ]
        (per_dir / f"{name}.pml").write_text("\n".join(l3) + "\n", encoding="utf-8")

    # 04 displacement putty + 05 PTM focus
    if profiles:
        write_pymol_displacement(conditions, baseline_name, profiles,
                                 pymol_dir, global_disp_max)
        write_pymol_ptm_focus(conditions, baseline_name, profiles,
                              pymol_dir, global_disp_max)

    # 06 clusters
    if cluster_labels:
        write_pymol_clusters(conditions, baseline_name, cluster_labels, pymol_dir,
                             cluster_separation=cluster_separation)

    _write_readme(pymol_dir, profiles is not None, bool(cluster_labels))
    _write_render_all(pymol_dir, conditions, baseline_name, profiles, cluster_labels)

    log.info("PyMOL scripts: %s", pymol_dir)


# ---------------------------------------------------------------------------
# Displacement putty
# ---------------------------------------------------------------------------

def _alter_bfactors(obj: str, profile: dict) -> List[str]:
    """Emit ``alter`` commands writing per-residue displacement into B."""
    lines = ["# overwrite B-factor with per-residue Cα displacement (Å)",
             f"alter {obj}, b=0.0"]
    res_numbers = profile.get("res_numbers", [])
    chain_ids = profile.get("chain_ids", [])
    disp = profile.get("disp_mean", [])
    for ch, rn, d in zip(chain_ids, res_numbers, disp):
        try:
            val = float(d)
        except (TypeError, ValueError):
            continue
        if val != val:  # NaN
            continue
        lines.append(f"alter {obj} and chain {ch} and resi {rn}, b={val:.3f}")
    lines.append("rebuild")
    return lines


def write_pymol_displacement(
    conditions: Dict[str, "object"],
    baseline_name: str,
    profiles: Dict[str, dict],
    pymol_dir: Path,
    global_disp_max: Optional[float],
) -> None:
    disp_dir = pymol_dir / "04_displacement_putty"
    disp_dir.mkdir(parents=True, exist_ok=True)
    base_cif = conditions[baseline_name].cif_path.resolve()
    ceil = f"{global_disp_max:.2f}" if global_disp_max else "10.0"

    for name, profile in profiles.items():
        if name not in conditions:
            continue
        cif = conditions[name].cif_path.resolve()
        obj = f"COND_{name}"
        l = _header(
            f"Displacement putty: {name} vs {baseline_name}",
            "tube radius + colour = per-residue Cα displacement (Å); "
            "blue=low, red=high",
        )
        l += [
            f"load {_rel(base_cif, disp_dir)}, BASE_{baseline_name}",
            f"color grey80, BASE_{baseline_name}",
            f"set cartoon_transparency, 0.5, BASE_{baseline_name}",
            "",
            f"load {_rel(cif, disp_dir)}, {obj}",
            f"align {obj}, BASE_{baseline_name}",
            "",
        ]
        l += _alter_bfactors(obj, profile)
        l += [
            "",
            "hide everything",
            f"show cartoon, BASE_{baseline_name} and polymer",
            f"show cartoon, {obj} and polymer",
            f"set cartoon_putty_scale_max, 4, {obj}",
            f"set cartoon_putty_radius, 0.4, {obj}",
            f"cartoon putty, {obj}",
            f"spectrum b, blue_white_red, {obj} and polymer, minimum=0, maximum={ceil}",
        ]
        # mark PTM sites on the moving structure
        for ch, rn, lab in _ptm_sites(conditions[name]):
            sel = f"{obj} and chain {ch} and resi {rn}"
            l += [
                f"show sticks, {sel}",
                f"color magenta, {sel}",
                f"label {sel} and name CA, '{lab}'",
            ]
        l += [
            "",
            f"zoom {obj} and polymer",
            "orient",
            f"# ray 1600, 1200; png {name}_displacement.png, dpi=300",
            "",
        ]
        (disp_dir / f"{name}.pml").write_text("\n".join(l) + "\n", encoding="utf-8")


# ---------------------------------------------------------------------------
# PTM focus close-ups
# ---------------------------------------------------------------------------

def write_pymol_ptm_focus(
    conditions: Dict[str, "object"],
    baseline_name: str,
    profiles: Dict[str, dict],
    pymol_dir: Path,
    global_disp_max: Optional[float],
) -> None:
    ptm_conditions = {
        n: c for n, c in conditions.items()
        if n != baseline_name and _ptm_sites(c)
    }
    if not ptm_conditions:
        return

    focus_dir = pymol_dir / "05_ptm_focus"
    focus_dir.mkdir(parents=True, exist_ok=True)
    base_cif = conditions[baseline_name].cif_path.resolve()
    ceil = f"{global_disp_max:.2f}" if global_disp_max else "10.0"

    for name, cond in ptm_conditions.items():
        profile = profiles.get(name, {})
        cif = cond.cif_path.resolve()
        obj = f"COND_{name}"
        sites = _ptm_sites(cond)
        site_sel = " or ".join(
            f"(chain {ch} and resi {rn})" for ch, rn, _ in sites
        )
        l = _header(
            f"PTM focus: {name}",
            "modified residue (magenta sticks) + baseline equivalent (grey), "
            "neighbourhood coloured by displacement",
        )
        l += [
            f"load {_rel(base_cif, focus_dir)}, BASE_{baseline_name}",
            f"load {_rel(cif, focus_dir)}, {obj}",
            f"align {obj}, BASE_{baseline_name}",
            "",
        ]
        l += _alter_bfactors(obj, profile)
        l += [
            "",
            "hide everything",
            f"show cartoon, {obj} and polymer",
            f"set cartoon_transparency, 0.15, {obj}",
            f"spectrum b, blue_white_red, {obj} and polymer, minimum=0, maximum={ceil}",
            "",
            f"# baseline equivalent residue(s) for reference",
            f"show cartoon, BASE_{baseline_name} and polymer",
            f"set cartoon_transparency, 0.7, BASE_{baseline_name}",
            f"color grey70, BASE_{baseline_name}",
            "",
        ]
        for ch, rn, lab in sites:
            sel = f"{obj} and chain {ch} and resi {rn}"
            bsel = f"BASE_{baseline_name} and chain {ch} and resi {rn}"
            l += [
                f"show sticks, {sel}",
                f"color magenta, {sel}",
                f"util.cnc {sel}",
                f"label {sel} and name CA, '{lab}'",
                f"show sticks, {bsel}",
                f"color grey50, {bsel}",
                f"# show neighbours within 6 A of the PTM",
                f"select near_{rn}, (byres ({obj} within 6 of ({sel}))) and {obj}",
                f"show sticks, near_{rn} and not name C+N+O",
            ]
        if site_sel:
            l += [
                "",
                f"zoom {obj} and ({site_sel}), 8",
                "orient",
                f"# ray 1600, 1200; png {name}_ptm_focus.png, dpi=300",
                "",
            ]
        (focus_dir / f"{name}.pml").write_text("\n".join(l) + "\n", encoding="utf-8")


